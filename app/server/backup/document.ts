import { z } from 'zod'
import {
  preferencesPatchSchema,
  actionPromptSchema,
  entryFaviconSchema,
} from '../../shared/contracts'

const stamp = z.string()
const stampOrNull = z.string().nullable()

const passphraseHeaderSchema = z.object({
  kdf: z.literal('pbkdf2-sha256'),
  iterations: z.number().int().positive(),
  salt: z.string(),
  check: z.string(),
})

export const backupDocumentSchema = z.object({
  format: z.literal(1),
  exportedAt: stamp,
  passphrase: passphraseHeaderSchema.optional(),
  users: z.array(
    z.object({
      id: z.string(),
      username: z.string(),
      email: z.string().nullable(),
      passwordHash: z.string().nullable(),
      role: z.enum(['viewer', 'editor', 'admin']),
      breakGlass: z.boolean(),
      authSource: z.enum(['local', 'oidc', 'header']),
      oidcIssuer: z.string().nullable(),
      oidcSubject: z.string().nullable(),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  preferences: z
    .array(
      preferencesPatchSchema.extend({
        userId: z.string(),
        createdAt: stamp,
        updatedAt: stamp,
      }),
    )
    .default([]),
  tokens: z.array(
    z.object({
      id: z.string(),
      userId: z.string(),
      name: z.string(),
      tokenHash: z.string(),
      scopes: z.array(z.enum(['read', 'write', 'admin'])),
      expiresAt: stampOrNull,
      lastUsedAt: stampOrNull,
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  namespaces: z.array(
    z.object({
      id: z.string(),
      name: z.string(),
      label: z.string(),
      colour: z.string(),
      sort: z.number(),
      showInSidebar: z.boolean(),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  tags: z.array(
    z.object({
      id: z.string(),
      namespaceName: z.string(),
      value: z.string(),
      displayLabel: z.string().nullable().optional(),
      createdAt: stamp,
      updatedAt: stamp,
    }),
  ),
  fieldDefinitions: z.array(
    z.object({
      id: z.string(),
      key: z.string(),
      label: z.string(),
      type: z.enum(['text', 'url', 'number', 'secret']),
      minRoleToView: z.enum(['anonymous', 'viewer', 'editor', 'admin']),
      searchable: z.boolean(),
      showAsColumnDefault: z.boolean(),
      sort: z.number(),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  entries: z.array(
    z.object({
      id: z.string(),
      name: z.string(),
      description: z.string(),
      host: z.string().nullable(),
      iconRef: z.string().nullable(),
      faviconUrl: entryFaviconSchema.default(null),
      sort: z.number(),
      source: z.string().nullable(),
      externalKey: z.string().nullable(),
      managedFields: z.array(z.string()),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  entryTags: z.array(
    z.object({
      entryId: z.string(),
      tagId: z.string(),
      createdAt: stamp,
      updatedAt: stamp,
    }),
  ),
  links: z.array(
    z.object({
      id: z.string(),
      entryId: z.string(),
      label: z.string(),
      urlTemplate: z.string(),
      type: z.enum(['web', 'api', 'ssh', 'vnc', 'rdp', 'telnet', 'other']),
      isPrimary: z.boolean(),
      sort: z.number(),
      iconRef: z.string().nullable(),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  fieldValues: z.array(
    z.object({
      id: z.string(),
      entryId: z.string(),
      fieldId: z.string(),
      valueText: z.string().nullable(),
      sealedSecret: z.string().optional(),
      secretRedacted: z.boolean().optional(),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  filters: z.array(
    z.object({
      id: z.string(),
      name: z.string(),
      query: z.string(),
      ownerUserId: z.string().nullable(),
      columns: z.array(z.string()),
      groupBy: z.string().nullable(),
      sort: z.number(),
      icon: z.string().nullable(),
      isPublic: z.boolean(),
      viewMode: z.enum(['list', 'cards', 'tiles']).default('list'),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  icons: z.array(
    z.object({
      id: z.string(),
      name: z.string(),
      kind: z.string(),
      mediaType: z.string().nullable(),
      hasData: z.boolean(),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  favicons: z.array(
    z.object({
      id: z.string(),
      origin: z.string(),
      sourceUrl: z.string().nullable().default(null),
      direct: z.boolean().default(false),
      status: z.string(),
      mediaType: z.string().nullable(),
      byteSize: z.number().nullable(),
      error: z.string().nullable(),
      fetchedAt: stampOrNull,
      hasData: z.boolean(),
      createdAt: stamp,
      updatedAt: stamp,
    }),
  ),
  checks: z.array(
    z.object({
      id: z.string(),
      entryId: z.string(),
      linkId: z.string().nullable(),
      name: z.string(),
      kind: z.enum(['icmp', 'tcp', 'http']),
      executor: z.enum(['server', 'client']),
      intervalSeconds: z.number(),
      timeoutMs: z.number(),
      tlsVerify: z.boolean(),
      host: z.string().nullable(),
      port: z.number().nullable(),
      requestSpec: z.record(z.string(), z.unknown()).nullable(),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  checkStatuses: z.array(
    z.object({
      checkId: z.string(),
      state: z.enum(['up', 'down', 'unknown']),
      latencyMs: z.number().nullable(),
      message: z.string(),
      checkedAt: stampOrNull,
      reportedBy: z.string().nullable(),
      createdAt: stamp,
      updatedAt: stamp,
    }),
  ),
  actions: z.array(
    z.object({
      id: z.string(),
      entryId: z.string(),
      name: z.string(),
      icon: z.string().nullable(),
      requestSpec: z.record(z.string(), z.unknown()),
      inputs: z.array(actionPromptSchema),
      confirm: z.boolean(),
      minRole: z.enum(['anonymous', 'viewer', 'editor', 'admin']),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  templates: z.array(
    z.object({
      id: z.string(),
      name: z.string(),
      icon: z.string().nullable(),
      requestSpec: z.record(z.string(), z.unknown()),
      inputs: z.array(actionPromptSchema),
      query: z.string(),
      confirm: z.boolean(),
      minRole: z.enum(['anonymous', 'viewer', 'editor', 'admin']),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
  audit: z.array(
    z.object({
      id: z.string(),
      actorId: z.string().nullable(),
      actorType: z.enum(['user', 'token', 'system']),
      actorLabel: z.string(),
      action: z.string(),
      targetType: z.string(),
      targetId: z.string().nullable(),
      diff: z.record(z.string(), z.unknown()),
      createdAt: stamp,
      updatedAt: stamp,
    }),
  ),
  settings: z.array(
    z.object({
      key: z.string(),
      value: z.unknown(),
      createdAt: stamp,
      updatedAt: stamp,
      updatedBy: z.string().nullable(),
    }),
  ),
  scopes: z.array(
    z.object({
      id: z.string(),
      name: z.string(),
      editMode: z.enum(['locked', 'field_ownership', 'free']),
      createdAt: stamp,
      updatedAt: stamp,
      createdBy: z.string().nullable(),
      updatedBy: z.string().nullable(),
    }),
  ),
})

export type BackupDocument = z.infer<typeof backupDocumentSchema>
